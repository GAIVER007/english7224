import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultPublicDir = path.join(projectRoot, ".output", "public");

const shellRoutes = ["/", "/translate", "/lesson", "/progress", "/placement", "/weekly", "/course"];
const shellFiles = new Set([
  "/favicon.ico",
  "/manifest.webmanifest",
  "/model-licenses.txt",
  "/icons/icon-180.png",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
]);

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);
      return entry.isDirectory() ? walk(entryPath) : [entryPath];
    }),
  );
  return files.flat();
}

function toPublicPath(file, publicDir) {
  return `/${path.relative(publicDir, file).split(path.sep).join("/")}`;
}

function shouldPrecache(file, publicDir) {
  const publicPath = toPublicPath(file, publicDir);
  if (shellFiles.has(publicPath)) return true;
  if (/\.(?:css|js|mjs)$/.test(publicPath)) return true;
  return publicPath.startsWith("/onnx/") && /\.(?:js|mjs|wasm|txt)$/.test(publicPath);
}

export async function generateOfflineWorker(publicDir = defaultPublicDir) {
  const outputFile = path.join(publicDir, "offline-worker.js");
  const allFiles = await walk(publicDir);
  const precacheFiles = allFiles.filter(
    (file) => file !== outputFile && shouldPrecache(file, publicDir),
  );
  const precacheUrls = precacheFiles.map((file) => toPublicPath(file, publicDir)).sort();
  const versionHash = createHash("sha256");

  for (const file of precacheFiles.sort()) {
    versionHash.update(toPublicPath(file, publicDir));
    versionHash.update(await readFile(file));
  }

  const cacheVersion = versionHash.digest("hex").slice(0, 12);
  const workerSource = `/* Generated by scripts/generate-offline.mjs. Do not edit by hand. */
const SHELL_CACHE = ${JSON.stringify(`speakup-shell-v${cacheVersion}`)};
const SHELL_CACHE_PREFIX = "speakup-shell-v";
const PRECACHE_URLS = ${JSON.stringify(precacheUrls, null, 2)};
const PRECACHE_PATHS = new Set(PRECACHE_URLS);
const SHELL_ROUTES = ${JSON.stringify(shellRoutes, null, 2)};

function localRequest(pathname, options = {}) {
  return new Request(new URL(pathname, self.location.origin), options);
}

async function cacheRequiredResponse(cache, pathname, isPage = false) {
  const request = localRequest(pathname, { cache: "reload" });
  const response = await fetch(request);
  if (!response.ok) throw new Error(\`Unable to cache \${pathname}: HTTP \${response.status}\`);
  const cacheKey = isPage ? localRequest(new URL(pathname, self.location.origin).pathname) : request;
  await cache.put(cacheKey, response);
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      try {
        const cache = await caches.open(SHELL_CACHE);
        await Promise.all(PRECACHE_URLS.map((pathname) => cacheRequiredResponse(cache, pathname)));
        await Promise.all(SHELL_ROUTES.map((pathname) => cacheRequiredResponse(cache, pathname, true)));
      } catch (error) {
        console.error("[SpeakUp offline] Shell installation failed.", error);
        throw error;
      }
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const cacheNames = await caches.keys();
      await Promise.all(
        cacheNames
          .filter((name) => name.startsWith(SHELL_CACHE_PREFIX) && name !== SHELL_CACHE)
          .map((name) => caches.delete(name)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;

  if (request.mode === "navigate") {
    event.respondWith(
      (async () => {
        const pageKey = localRequest(url.pathname);
        try {
          const response = await fetch(request);
          if (response.ok) {
            const copy = response.clone();
            event.waitUntil(
              caches.open(SHELL_CACHE).then((cache) => cache.put(pageKey, copy)).catch(() => undefined),
            );
            return response;
          }
          const cached = await caches.match(pageKey, { cacheName: SHELL_CACHE });
          return cached ?? response;
        } catch {
          const cache = await caches.open(SHELL_CACHE);
          return (await cache.match(pageKey)) ?? (await cache.match(localRequest("/"))) ?? Response.error();
        }
      })(),
    );
    return;
  }

  if (!PRECACHE_PATHS.has(url.pathname)) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(SHELL_CACHE);
      const cached = await cache.match(request);
      if (cached) return cached;
      const response = await fetch(request);
      if (response.ok) {
        const copy = response.clone();
        event.waitUntil(cache.put(request, copy).catch(() => undefined));
      }
      return response;
    })(),
  );
});
`;

  await writeFile(outputFile, workerSource);
  console.log(
    `Generated ${path.relative(projectRoot, outputFile)} (${precacheUrls.length} files, cache ${cacheVersion}).`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateOfflineWorker();
}
