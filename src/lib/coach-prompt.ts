import { lessons } from "./content";
import { mistakeWords } from "./mistakes";
import type { AppState } from "./store";

export const coachModes = {
  conversation: "Разговор",
  mistakes: "Разбор ошибок",
  practice: "Тренировка на 10 минут",
} as const;
export type CoachMode = keyof typeof coachModes;

/** Explicit, small learning summary; no raw storage, activity dates or personal text. */
export function coachPrompt(state: AppState, mode: CoachMode): string {
  const lesson = lessons[Math.min(state.day - 1, lessons.length - 1)]!;
  const words = mistakeWords(state).map((word) => `${word.en} — ${word.ru}`);
  const history = (state.grammarHistory ?? []).slice(-20);
  const goal = {
    conversation:
      "Начни ролевой диалог по текущей теме. Пиши одну короткую реплику на английском и жди моего ответа. После ответа исправь максимум две важные ошибки, кратко объясни их по-русски и продолжи разговор.",
    mistakes:
      "Помоги закрепить трудные слова и построение предложений. Не выдумывай мои прошлые ошибки: конкретных ответов у тебя нет. Дай одно диагностическое задание, дождись ответа, затем объясни ошибку и предложи похожее задание без готового ответа.",
    practice:
      "Проведи тренировку примерно на 10 минут: вспоминание слов, построение фраз, короткий диалог. Давай по одному заданию и жди ответа. В конце кратко назови, что получилось и что повторить.",
  }[mode];
  return [
    "Ты мой персональный наставник по английскому. Я учусь для себя: хочу понимать речь и увереннее разговаривать.",
    `Мой выбранный уровень в приложении: ${state.level ?? "ещё не определён"}. Это ориентир, а не подтверждённый результат CEFR. Подстрой сложность по моим ответам.`,
    `Текущая тема: ${lesson.titleRu} (${lesson.title}). Завершено миссий: ${Math.min(state.day - 1, lessons.length)} из ${lessons.length}.`,
    words.length
      ? `Слова, которые пока требуют закрепления: ${words.join(", ")}.`
      : "Слов с незакреплёнными ошибками пока нет в статистике.",
    history.length
      ? `Свободный грамматический тренажёр: ${history.filter(Boolean).length} верных ответов из последних ${history.length}. Точных ошибочных фраз в статистике нет.`
      : "Результатов свободного грамматического тренажёра пока нет.",
    goal,
    "Не показывай ответ до моей попытки. Если я прошу помощь, сначала дай подсказку. Используй естественный английский, объясняй кратко по-русски. Не оценивай произношение по тексту и не заявляй, что можешь обновить прогресс приложения.",
    "Начни с первого задания сейчас.",
  ].join("\n\n");
}
