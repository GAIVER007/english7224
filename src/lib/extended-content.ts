import type { DialogueLine, Lesson, Word } from "./content";

type WordInput = [string, string, string, string, string, string, string, string];
type LineInput = [string, string];

function word([id, en, ru, ipa, example, exampleRu, phraseEn, phraseRu]: WordInput): Word {
  return { id, en, ru, ipa, example, exampleRu, phrases: [{ en: phraseEn, ru: phraseRu }] };
}

function dialogue(...lines: LineInput[]): DialogueLine[] {
  return lines.map(([en, ru], index) => ({ who: index % 2 === 0 ? "A" : "B", en, ru }));
}

